"""Build the Singapore MOE Primary courses and coverage report from the curriculum mapping.

The mapping in `data/curricula/sg-moe-primary-2021.json` is the source of truth: one row per
learning outcome in the MOE 2021 Primary Mathematics syllabus (P1-P6, Standard), with the Orchid
concepts that practise it and how fully. This script derives everything else from it:

  * `data/courses.json` -- the `sg-p1` .. `sg-p6` courses (other courses are left alone).
  * `data/destinations.json` -- the `sg-moe-primary` destination.
  * `docs/curriculum/sg-moe-primary.md` -- the coverage report a parent or teacher can read.
  * `web/next-app/data/moe.coverage.json` -- the per-level counts the landing page shows.
  * `web/next-app/data/moe.levels.json` -- each level's course, topics and concepts, which the
    level picker and the levels page are built from.

A level's course does not simply target the concepts mapped at that level. The concept graph was
built for another sequence, so a concept can depend on something the syllabus places later: comparing
whole numbers is a P1 outcome, but Orchid's generator for it reaches into the thousands and so sits
behind thousands place value (P3). Each concept therefore gets an *effective level* -- the latest of
its own level and every prerequisite's -- and Primary N targets only concepts whose effective level
is N or earlier. A prerequisite the syllabus never mentions does not move the level, but the report
lists it, because a learner will meet it.

Run from the repo root: `python3 scripts/curriculum_moe.py` (or `--check` to fail on drift).
"""
import json
import os
import sys

MAPPING = "data/curricula/sg-moe-primary-2021.json"
COURSES = "data/courses.json"
DESTINATIONS = "data/destinations.json"
REPORT = "docs/curriculum/sg-moe-primary.md"
LANDING = "web/next-app/data/moe.coverage.json"
LEVELS_JSON = "web/next-app/data/moe.levels.json"
LEVELS = ["P1", "P2", "P3", "P4", "P5", "P6"]
LEVEL_NAMES = {f"P{i}": f"Primary {i}" for i in range(1, 7)}


def load_concepts():
    out = {}
    for f in sorted(os.listdir("data/concepts")):
        for c in json.load(open(os.path.join("data/concepts", f), encoding="utf-8")):
            if "id" in c:
                out[c["id"]] = c
    return out


def effective_levels(doc, concepts):
    first = {}
    for o in doc["outcomes"]:
        for c in o["concepts"]:
            if c not in first or LEVELS.index(o["level"]) < LEVELS.index(first[c]):
                first[c] = o["level"]
    memo, extra = {}, {}

    def walk(cid):
        if cid in memo:
            return memo[cid]
        memo[cid] = first.get(cid, "P1")  # cycle guard; the graph is a DAG
        lvl = LEVELS.index(first.get(cid, "P1"))
        beyond = set()
        for p in concepts[cid].get("prerequisites", []):
            pl = walk(p)
            if p in first:
                lvl = max(lvl, LEVELS.index(pl))
            else:
                beyond.add(p)
            beyond |= extra.get(p, set())
        memo[cid] = LEVELS[lvl]
        extra[cid] = beyond
        return memo[cid]

    for c in first:
        walk(c)
    return first, {c: memo[c] for c in first}, {c: extra[c] for c in first}


def build(doc, concepts):
    first, eff, beyond = effective_levels(doc, concepts)
    courses = []
    for i, lvl in enumerate(LEVELS):
        targets = sorted(c for c in first if LEVELS.index(eff[c]) <= i and LEVELS.index(first[c]) <= i)
        topics = []
        for o in doc["outcomes"]:
            if o["level"] == lvl and o["topic"] not in topics:
                topics.append(o["topic"])
        courses.append({
            "id": f"sg-{lvl.lower()}",
            "name": f"{LEVEL_NAMES[lvl]} Mathematics (MOE)",
            "grade": lvl,
            "description": f"Mapped to the MOE 2021 Primary Mathematics syllabus, {LEVEL_NAMES[lvl]}: "
                           + ", ".join(topics) + ". See the coverage report for what is and is not practised.",
            "targets": targets,
        })
    return first, eff, beyond, courses


def report(doc, concepts, first, eff, beyond, courses):
    labels = {c: concepts[c].get("label", c) for c in concepts}
    lines = [
        "# Singapore Primary Mathematics: coverage report",
        "",
        f"Source: [{doc['source']['title']}]({doc['source']['url']}), {doc['source']['section']}. "
        f"Retrieved {doc['source']['retrieved']}.",
        "",
        f"> {doc['disclaimer']}",
        "",
        "Generated by `scripts/curriculum_moe.py` from `data/curricula/sg-moe-primary-2021.json`. Do not edit by hand.",
        "",
        "## Coverage levels",
        "",
    ]
    for k, v in doc["coverage_levels"].items():
        lines.append(f"- **{k}**: {v}")
    lines += ["", "## Summary", "", "| Level | Outcomes | Full | Partial | None | Concepts targeted (cumulative) |", "|---|---|---|---|---|---|"]
    tot = {"n": 0, "full": 0, "partial": 0, "none": 0}
    for lvl, course in zip(LEVELS, courses):
        rows = [o for o in doc["outcomes"] if o["level"] == lvl]
        cnt = {k: sum(1 for o in rows if o["coverage"] == k) for k in ("full", "partial", "none")}
        tot["n"] += len(rows)
        for k in cnt:
            tot[k] += cnt[k]
        lines.append(f"| {LEVEL_NAMES[lvl]} | {len(rows)} | {cnt['full']} | {cnt['partial']} | {cnt['none']} | {len(course['targets'])} |")
    lines.append(f"| **All** | {tot['n']} | {tot['full']} | {tot['partial']} | {tot['none']} | |")
    lines += [""]

    late = sorted((c for c in first if eff[c] != first[c]), key=lambda c: (LEVELS.index(first[c]), c))
    if late:
        lines += ["## Practised later than the syllabus places it", "",
                  "These concepts depend on something the syllabus teaches later, so Orchid's course for the "
                  "syllabus level does not include them yet.", "",
                  "| Concept | Syllabus level | Practised from |", "|---|---|---|"]
        lines += [f"| {labels[c]} (`{c}`) | {first[c]} | {eff[c]} |" for c in late]
        lines.append("")
    ext = sorted({p for c in first for p in beyond[c]})
    if ext:
        lines += ["## Prerequisites beyond the primary syllabus", "",
                  "The concept graph puts these in front of some mapped concepts, so a learner will meet them "
                  "although the primary syllabus does not include them.", "",
                  "| Prerequisite | Needed before |", "|---|---|"]
        for p in ext:
            needed = sorted(c for c in first if p in beyond[c])
            lines.append(f"| {labels[p]} (`{p}`) | " + ", ".join(f"`{c}`" for c in needed[:6])
                         + (f" and {len(needed) - 6} more" if len(needed) > 6 else "") + " |")
        lines.append("")

    mark = {"full": "Full", "partial": "Partial", "none": "**None**"}
    for lvl in LEVELS:
        lines += [f"## {LEVEL_NAMES[lvl]}", ""]
        topic = None
        for o in (o for o in doc["outcomes"] if o["level"] == lvl):
            if (o["strand"], o["sub_strand"], o["topic"]) != topic:
                topic = (o["strand"], o["sub_strand"], o["topic"])
                lines += ["", f"### {o['topic']}", f"*{o['strand']} / {o['sub_strand']}*", "",
                          "| Ref | Outcome | Coverage | Orchid concepts | Note |", "|---|---|---|---|---|"]
            cs = ", ".join(labels[c] for c in o["concepts"]) or "-"
            lines.append(f"| {o['id']} | {o['outcome']} | {mark[o['coverage']]} | {cs} | {o['note']} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def landing(doc, first):
    """Per-level outcome counts for the landing page, which must not hand-write them (AGENTS.md §7)."""
    levels = []
    for lvl in LEVELS:
        rows = [o for o in doc["outcomes"] if o["level"] == lvl]
        counts = {k: sum(1 for o in rows if o["coverage"] == k) for k in ("full", "partial", "none")}
        levels.append({"level": lvl, "name": LEVEL_NAMES[lvl], "outcomes": len(rows), **counts})
    return {"outcomeCount": len(doc["outcomes"]), "conceptCount": len(first), "levels": levels}


def levels_view(doc, concepts, courses):
    """Each level as a learner browses it: its course, then its syllabus topics in order."""
    out = []
    for lvl, course in zip(LEVELS, courses):
        topics = []
        for o in doc["outcomes"]:
            if o["level"] != lvl:
                continue
            # The same topic name recurs under different sub-strands ("Four Operations" for whole
            # numbers and for fractions), so a topic is the pair, not the name.
            t = next((x for x in topics if x["topic"] == o["topic"] and x["strand"] == o["sub_strand"]), None)
            if t is None:
                t = {"topic": o["topic"], "strand": o["sub_strand"], "full": 0, "partial": 0, "none": 0, "concepts": []}
                topics.append(t)
            t[o["coverage"]] += 1
            for c in o["concepts"]:
                if all(x["id"] != c for x in t["concepts"]):
                    t["concepts"].append({"id": c, "label": concepts[c]["label"]})
        out.append({"level": lvl, "name": LEVEL_NAMES[lvl], "courseId": course["id"], "targets": course["targets"], "topics": topics})
    return out


def dump(obj):
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def main():
    check = "--check" in sys.argv
    doc = json.load(open(MAPPING, encoding="utf-8"))
    concepts = load_concepts()
    first, eff, beyond, courses = build(doc, concepts)

    existing = json.load(open(COURSES, encoding="utf-8"))
    kept = [c for c in existing if not c["id"].startswith("sg-")]
    new_courses = dump(courses + kept)

    dests = json.load(open(DESTINATIONS, encoding="utf-8"))
    dests = [d for d in dests if d["id"] != "sg-moe-primary"]
    dests.insert(0, {
        "id": "sg-moe-primary",
        "name": "Singapore Primary Mathematics (MOE)",
        "description": "Primary 1 to 6, mapped to the MOE 2021 Primary Mathematics syllabus.",
        "courses": [c["id"] for c in courses],
    })
    new_dests = dump(dests)
    new_report = report(doc, concepts, first, eff, beyond, courses)

    outputs = {COURSES: new_courses, DESTINATIONS: new_dests, REPORT: new_report, LANDING: dump(landing(doc, first)),
               LEVELS_JSON: dump(levels_view(doc, concepts, courses))}
    stale = [p for p, s in outputs.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != s]
    if check:
        if stale:
            sys.exit("stale, run python3 scripts/curriculum_moe.py: " + ", ".join(stale))
        return
    for p in stale:
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w", encoding="utf-8").write(outputs[p])
    for c in courses:
        print(f"{c['id']}: {len(c['targets'])} targets")


if __name__ == "__main__":
    main()
